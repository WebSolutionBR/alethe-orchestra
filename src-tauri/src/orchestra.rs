/// Next worker number of each session, so every orchestration numbers its own `claude-N`.
struct Counters(Mutex<BTreeMap<String, u32>>);

impl Counters {
    const fn new() -> Self {
        Self(Mutex::new(BTreeMap::new()))
    }

    fn lock(&self) -> MutexGuard<'_, BTreeMap<String, u32>> {
        // Recover from poisoning: the map stays consistent and release builds abort on panic.
        self.0.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Takes the session's next number; a session without a counter starts at 1.
    fn next(&self, session: &str) -> u32 {
        let mut counters = self.lock();
        let next = counters.entry(session.to_string()).or_insert(1);
        let id = *next;
        *next = id.saturating_add(1);
        id
    }

    fn reset(&self, session: &str) {
        self.lock().insert(session.to_string(), 1);
    }

    /// Makes the session's next number at least `next`; a number already handed out is never
    /// handed out again.
    fn seed(&self, session: &str, next: u32) {
        let mut counters = self.lock();
        let entry = counters.entry(session.to_string()).or_insert(1);
        *entry = (*entry).max(next.max(1));
    }

    fn forget(&self, session: &str) {
        self.lock().remove(session);
    }
}

