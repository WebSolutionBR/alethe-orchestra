//! Orchestra: an orchestrator Claude session coordinating worker Claude sessions.
//!
//! Several orchestrations can run at once. Each one is a session with its own id, its own
//! orchestrator and its own `claude-1…N` numbering. Agents reach the app through the `orch`
//! CLI helper (written to the temp dir by `orchestra_prepare`), which posts to
//! `/orchestra/<action>` on the agent listener in `agent_events.rs` with the agent's
//! `ALETHE_ORCHESTRA_SESSION`; Claude Code hooks post to `/orchestra/hook/<session>/<agent>`.
//! Calls that carry no session (agents started by an older build) belong to the `default`
//! session. Each accepted call is re-emitted to the frontend as a single `orchestra://event`
//! tagged with its `session`, so every view renders from the same stream and keeps only the
//! sessions it runs.
//!
//! Free text never has to cross a command line: `orch` takes it from `--file`/`--stdin`, and an
//! agent's task (or the orchestrator's goal) is handed over as a `task-<session>-<agent>.md`
//! file. A manifest per running session (in the profile's app data) lets an orchestration
//! that was cut short by closing the app be read again and resumed.

