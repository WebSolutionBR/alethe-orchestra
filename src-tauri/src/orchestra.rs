/// cmd.exe entry point. `%*` still passes through cmd, so free text belongs in `--file`.
const CLI_CMD: &str = "@echo off\r\nsetlocal\r\nset \"ALETHE_ORCHESTRA_CLI=wrapper\"\r\npowershell -NoProfile -ExecutionPolicy Bypass -File \"%~dp0orch.ps1\" %*\r\nexit /b %ERRORLEVEL%\r\n";

/// `orch` for sh and bash (Git Bash): runs `orch.ps1` without cmd.exe in between.
const CLI_SH: &str = r##"#!/bin/sh
# orch - Alethe Orchestra bridge for sh and bash (Git Bash). Generated by the app; edits are
# overwritten. It runs orch.ps1 in powershell.exe directly, never through cmd.exe, so quotes,
# & | > % and line breaks in arguments arrive intact. Only the path after --file becomes a
# Windows path; MSYS path conversion stays off for the rest, so text like /compact is kept.
script="$(dirname "$0")/orch.ps1"
if command -v cygpath >/dev/null 2>&1; then
  script=$(cygpath -w "$script")
  path_next=
  for arg do
    shift
    if [ -n "$path_next" ]; then
      arg=$(cygpath -w -- "$arg")
      path_next=
    else
      case $arg in
        --file) path_next=1 ;;
        --file=*) arg="--file=$(cygpath -w -- "${arg#--file=}")" ;;
      esac
    fi
    set -- "$@" "$arg"
  done
fi
export ALETHE_ORCHESTRA_CLI=wrapper MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*'
exec powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$script" "$@"
"##;

