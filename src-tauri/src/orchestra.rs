fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

fn work_dir() -> PathBuf {
    std::env::temp_dir().join("alethe-orchestra")
}

/// Rule shared by session and agent ids; they end up in file names and URL paths.
fn is_valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 32
        && id
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

fn clip(text: &str, max: usize) -> String {
    let trimmed = text.trim();
    if trimmed.chars().count() <= max {
        return trimmed.to_string();
    }
    let mut out: String = trimmed.chars().take(max).collect();
    out.push('…');
    out
}

/// `clip`, plus whether anything was cut, so the CLI can tell the agent.
fn clip_flagged(text: &str, max: usize) -> (String, bool) {
    (clip(text, max), text.trim().chars().count() > max)
}

/// Reply of an accepted call; a cut text adds `clipped` and the `limit` it was cut to.
fn ok_body(mut body: Value, clipped: bool, limit: usize) -> String {
    if clipped {
        body["clipped"] = json!(true);
        body["limit"] = json!(limit);
    }
    body.to_string()
}

fn str_field(value: &Value, key: &str) -> String {
    value
        .get(key)
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string()
}

/// Writes through a sibling temp file and a rename, so a reader never sees half a file; when the
/// rename fails the old file stays as it was and the error is returned.
fn replace_file(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let mut tmp = path.as_os_str().to_owned();
    tmp.push(".tmp");
    let tmp = PathBuf::from(tmp);
    std::fs::write(&tmp, bytes).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        e.to_string()
    })
}

/// `replace_file`, falling back to writing in place when Windows refuses the rename (the
/// target is open elsewhere); for files whose next reader only needs the latest content.
fn write_atomic(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if replace_file(path, bytes).is_ok() {
        return Ok(());
    }
    std::fs::write(path, bytes).map_err(|e| e.to_string())
}

/// Agents of every session run the same scripts, so only rewrite one when this build changed
/// it instead of replacing it under a running `orch` call.
fn write_if_changed(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if std::fs::read(path).is_ok_and(|current| current == bytes) {
        return Ok(());
    }
    write_atomic(path, bytes)
}

/// Writes `orch.ps1`, `orch.cmd` and the `orch` sh shim into `dir`.
fn write_cli_in(dir: &Path) -> Result<(), String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    // A UTF-8 BOM keeps Windows PowerShell 5.1 from reading the script as ANSI.
    let mut ps1 = vec![0xEF, 0xBB, 0xBF];
    ps1.extend_from_slice(CLI_PS1.as_bytes());
    write_if_changed(&dir.join("orch.ps1"), &ps1)?;
    write_if_changed(&dir.join("orch.cmd"), CLI_CMD.as_bytes())?;
    // sh reads a `\r` as part of the command, so the shim stays LF even from a CRLF checkout.
    write_if_changed(&dir.join("orch"), CLI_SH.replace("\r\n", "\n").as_bytes())?;
    Ok(())
}

fn write_cli() -> Result<PathBuf, String> {
    let dir = work_dir().join("bin");
    write_cli_in(&dir)?;
    Ok(dir)
}

fn write_hook_settings(
    dir: &Path,
    endpoint: &str,
    token: &str,
    session: &str,
    agent_id: &str,
) -> Result<PathBuf, String> {
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let hook = json!([{ "hooks": [{
        "type": "http",
        "url": format!("{endpoint}/orchestra/hook/{session}/{agent_id}"),
        "timeout": 5,
        "headers": { "X-Alethe-Token": token }
    }] }]);
    let settings = json!({
        "hooks": {
            "UserPromptSubmit": hook.clone(),
            "PreToolUse": hook.clone(),
            "PostToolUse": hook.clone(),
            "Notification": hook.clone(),
            "SubagentStart": hook.clone(),
            "SubagentStop": hook.clone(),
            "Stop": hook
        }
    });
    let path = dir.join(format!("hooks-{session}-{agent_id}.json"));
    let body = serde_json::to_string_pretty(&settings).map_err(|e| e.to_string())?;
    std::fs::write(&path, body).map_err(|e| e.to_string())?;
    Ok(path)
}

/// Writes an agent's task (or the orchestrator's goal) to `task-<session>-<agent>.md` in `dir`.
fn write_task_file(
    dir: &Path,
    session: &str,
    agent_id: &str,
    text: &str,
) -> Result<PathBuf, String> {
    if text.len() > MAX_TASK_BYTES {
        return Err(format!("task is larger than {} KB", MAX_TASK_BYTES / 1024));
    }
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let path = dir.join(format!("task-{session}-{agent_id}.md"));
    write_atomic(&path, text.as_bytes())?;
    Ok(path)
}

/// Deletes `task-*.md` files older than `max_age`; best effort.
fn prune_stale_tasks(dir: &Path, max_age: Duration) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let now = SystemTime::now();
    for entry in entries.flatten() {
        let name = entry.file_name();
        let is_task = name
            .to_str()
            .is_some_and(|name| name.starts_with("task-") && name.ends_with(".md"));
        let stale = entry
            .metadata()
            .and_then(|meta| meta.modified())
            .ok()
            .and_then(|modified| now.duration_since(modified).ok())
            .is_some_and(|age| age > max_age);
        if is_task && stale {
            let _ = std::fs::remove_file(entry.path());
        }
    }
}

/// Deletes the session's `hooks-<session>-<agent>.json` and `task-<session>-<agent>.md` files
/// in `dir`; returns how many went. Frontend session ids have no `-`, so the prefixes cannot
/// match another session's files.
fn remove_session_files(dir: &Path, session: &str) -> usize {
    let kinds = [
        (format!("hooks-{session}-"), ".json"),
        (format!("task-{session}-"), ".md"),
    ];
    let Ok(entries) = std::fs::read_dir(dir) else {
        return 0;
    };
    let mut removed = 0;
    for entry in entries.flatten() {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        let ours = kinds.iter().any(|(prefix, suffix)| {
            name.strip_prefix(prefix.as_str())
                .and_then(|rest| rest.strip_suffix(suffix))
                .is_some_and(is_valid_id)
        });
        if ours && std::fs::remove_file(entry.path()).is_ok() {
            removed += 1;
        }
    }
    removed
}

/// Starts a fresh numbering of workers (claude-1, claude-2, ...) for one session; other
/// sessions keep theirs.
#[tauri::command]
pub fn orchestra_reset(session_id: String) {
    if is_valid_id(&session_id) {
        COUNTERS.reset(&session_id);
    }
}

/// A resumed session keeps numbering after its highest `claude-N`, so a new spawn never takes
/// the id of a worker that already exists (the frontend drops a spawn whose id it knows).
#[tauri::command]
pub fn orchestra_resume(session_id: String, next_worker: u32) {
    if is_valid_id(&session_id) {
        COUNTERS.seed(&session_id, next_worker);
    }
}

/// Whether `path` is an existing folder (empty means no).
fn is_folder(path: &str) -> bool {
    !path.trim().is_empty() && Path::new(path).is_dir()
}

/// Refuses a launch whose folder is gone: the PTY would fall back to the home folder and an
/// agent (autonomous, maybe) would work there instead.
fn check_cwd(cwd: Option<&str>) -> Result<(), String> {
    match cwd {
        Some(cwd) if !is_folder(cwd) => Err(format!("folder not found: {cwd}")),
        _ => Ok(()),
    }
}

/// Whether a folder exists, so a resume can be refused before it starts.
#[tauri::command]
pub fn orchestra_folder_exists(path: String) -> bool {
    is_folder(&path)
}

/// Writes the CLI helper and the agent's hooks settings for its session, and returns what
/// the frontend needs to spawn that agent's PTY. With `cwd`, a folder that no longer exists
/// fails the launch instead of letting it run elsewhere.
#[tauri::command]
pub fn orchestra_prepare(
    session_id: String,
    agent_id: String,
    cwd: Option<String>,
) -> Result<OrchestraLaunch, String> {
    if !is_valid_id(&session_id) {
        return Err(format!("invalid session id: {session_id}"));
    }
    if !is_valid_id(&agent_id) {
        return Err(format!("invalid agent id: {agent_id}"));
    }
    check_cwd(cwd.as_deref())?;
    let endpoint = crate::agent_events::current_endpoint()?;
    let token = crate::agent_events::current_token();
    let bin = write_cli()?;
    let settings = write_hook_settings(&work_dir(), &endpoint, &token, &session_id, &agent_id)?;
    let current_path = std::env::var("PATH").unwrap_or_default();
    Ok(OrchestraLaunch {
        endpoint,
        token,
        settings_path: settings.to_string_lossy().to_string(),
        cli_path: bin.join("orch.cmd").to_string_lossy().to_string(),
        path_env: format!("{};{}", bin.to_string_lossy(), current_path),
    })
}

/// Saves an agent's task (or the orchestrator's goal) as `task-<session>-<agent>.md` in the
/// work dir and returns its path. The agent is told to read that file, so the text never goes
/// through a command line, where PowerShell 5.1 and cmd.exe mangle quotes, `%`, `&` and line
/// breaks.
#[tauri::command]
pub fn orchestra_write_task(
    session_id: String,
    agent_id: String,
    text: String,
) -> Result<String, String> {
    if !is_valid_id(&session_id) {
        return Err(format!("invalid session id: {session_id}"));
    }
    if !is_valid_id(&agent_id) {
        return Err(format!("invalid agent id: {agent_id}"));
    }
    let dir = work_dir();
    prune_stale_tasks(&dir, TASK_FILE_MAX_AGE);
    let path = write_task_file(&dir, &session_id, &agent_id, &text)?;
    Ok(path.to_string_lossy().into_owned())
}

/// Forgets a finished session: its worker numbering, its hooks settings and its task files.
/// Best effort, so stopping a session never fails here.
#[tauri::command]
pub fn orchestra_end(session_id: String) {
    if !is_valid_id(&session_id) {
        return;
    }
    COUNTERS.forget(&session_id);
    crate::orchestra_accounts::forget(&session_id);
    remove_session_files(&work_dir(), &session_id);
}

fn manifests_dir(app: &AppHandle) -> Result<PathBuf, String> {
    Ok(crate::paths::profile_data_dir(app)?.join("orchestra"))
}

/// The session id of a `<session>.json` manifest path.
fn manifest_session(path: &Path) -> Option<String> {
    if path.extension()? != "json" {
        return None;
    }
    let stem = path.file_stem()?.to_str()?;
    is_valid_id(stem).then(|| stem.to_string())
}

fn manifest_sessions_in(dir: &Path) -> Vec<String> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut sessions: Vec<String> = entries
        .flatten()
        .filter_map(|entry| manifest_session(&entry.path()))
        .collect();
    sessions.sort();
    sessions
}

fn save_manifest_in(dir: &Path, session: &str, manifest: &Value) -> Result<(), String> {
    if !is_valid_id(session) {
        return Err(format!("invalid session id: {session}"));
    }
    if !manifest.is_object() {
        return Err("a manifest is a JSON object".to_string());
    }
    let bytes = serde_json::to_vec(manifest).map_err(|e| e.to_string())?;
    if bytes.len() > MAX_MANIFEST_BYTES {
        return Err(format!(
            "manifest is larger than {} KB",
            MAX_MANIFEST_BYTES / 1024
        ));
    }
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    // Never written in place: a manifest is either the old one or the new one, whole.
    replace_file(&dir.join(format!("{session}.json")), &bytes)
}

/// A session's manifest when it can be used: a JSON object of a version this build reads.
fn read_manifest(dir: &Path, session: &str) -> Option<Map<String, Value>> {
    let bytes = std::fs::read(dir.join(format!("{session}.json"))).ok()?;
    if bytes.len() > MAX_MANIFEST_BYTES {
        return None;
    }
    let Value::Object(manifest) = serde_json::from_slice(&bytes).ok()? else {
        return None;
    };
    (manifest.get("version").and_then(Value::as_u64) == Some(MANIFEST_VERSION)).then_some(manifest)
}

/// Every manifest in `dir`, each with `id` set to its file's session. One that cannot be read
/// (damaged, or written by a newer build) comes as `{ id, damaged: true }`, so it can still
/// be discarded instead of lingering unseen.
fn list_manifests_in(dir: &Path) -> Vec<Value> {
    manifest_sessions_in(dir)
        .into_iter()
        .map(|session| match read_manifest(dir, &session) {
            Some(mut manifest) => {
                manifest.insert("id".into(), Value::String(session));
                Value::Object(manifest)
            }
            None => json!({ "id": session, "damaged": true }),
        })
        .collect()
}

/// Scrollback file prefix of a session's agents (`orchestra-<session>-<agent>-<time>.bin`).
fn scrollback_prefix(session: &str) -> String {
    format!("orchestra-{session}-")
}

/// Removes a session's manifest and, from `scrollback`, the `.bin` files its agents left
/// behind; returns how many files went. Best effort.
fn remove_manifest_in(dir: &Path, scrollback: Option<&Path>, session: &str) -> usize {
    if !is_valid_id(session) {
        return 0;
    }
    let mut removed = 0;
    for name in [format!("{session}.json"), format!("{session}.json.tmp")] {
        if std::fs::remove_file(dir.join(name)).is_ok() {
            removed += 1;
        }
    }
    let prefix = scrollback_prefix(session);
    let Some(entries) = scrollback.and_then(|dir| std::fs::read_dir(dir).ok()) else {
        return removed;
    };
    for entry in entries.flatten() {
        let name = entry.file_name();
        let ours = name
            .to_str()
            .is_some_and(|name| name.starts_with(&prefix) && name.ends_with(".bin"));
        if ours && std::fs::remove_file(entry.path()).is_ok() {
            removed += 1;
        }
    }
    removed
}

/// Scrollback prefixes of the sessions in `dir` with a usable manifest; a damaged one protects
/// nothing.
fn kept_prefixes_in(dir: &Path) -> Vec<String> {
    manifest_sessions_in(dir)
        .into_iter()
        .filter(|session| read_manifest(dir, session).is_some())
        .map(|session| scrollback_prefix(&session))
        .collect()
}

/// Scrollback prefixes of sessions that still have a manifest. The startup sweep in `pty.rs`
/// keeps their `.bin` files, so an orchestration cut short by closing the app stays readable.
pub(crate) fn kept_scrollback_prefixes(app: &AppHandle) -> Vec<String> {
    manifests_dir(app)
        .map(|dir| kept_prefixes_in(&dir))
        .unwrap_or_default()
}

/// Saves the manifest of a running session (atomically; the frontend debounces the calls).
#[tauri::command]
pub async fn orchestra_manifest_save(
    app: AppHandle,
    session_id: String,
    manifest: Value,
) -> Result<(), String> {
    save_manifest_in(&manifests_dir(&app)?, &session_id, &manifest)
}

/// Manifests of every session that was still running when the app last closed (or of the
/// ones running now).
#[tauri::command]
pub async fn orchestra_manifest_list(app: AppHandle) -> Result<Vec<Value>, String> {
    Ok(list_manifests_in(&manifests_dir(&app)?))
}

/// Forgets a session's manifest and the scrollback kept for it.
#[tauri::command]
pub async fn orchestra_manifest_remove(app: AppHandle, session_id: String) -> Result<(), String> {
    if !is_valid_id(&session_id) {
        return Err(format!("invalid session id: {session_id}"));
    }
    let scrollback = crate::paths::scrollback_dir(&app).ok();
    remove_manifest_in(&manifests_dir(&app)?, scrollback.as_deref(), &session_id);
    Ok(())
}

/// A Claude Code conversation id: a UUID. It ends up as `claude --resume <id>` on a command
/// line (through cmd.exe for a `.cmd` launcher), so nothing else is accepted.
fn is_conversation_id(id: &str) -> bool {
    id.len() == 36
        && id.char_indices().all(|(i, c)| match i {
            8 | 13 | 18 | 23 => c == '-',
            _ => c.is_ascii_hexdigit(),
        })
}

/// A conversation transcript as Claude Code keeps it: an absolute `.jsonl` path inside a
/// `projects` folder (of its config dir), with no `..`.
fn is_transcript_path(path: &str) -> bool {
    let path = Path::new(path);
    path.is_absolute()
        && path.extension().is_some_and(|ext| ext == "jsonl")
        && path.components().any(|part| part.as_os_str() == "projects")
        && !path
            .components()
            .any(|part| matches!(part, std::path::Component::ParentDir))
}

/// Keeps only what the views render; raw hook payloads can carry whole files. The ids of the
/// agent's Claude conversation (`session_id`, `transcript_path`) let a session be resumed;
/// any hook may post here, so they pass only in the shape Claude Code gives them.
fn summarize_hook(payload: &Value) -> Value {
    let mut out = Map::new();
    for key in [
        "hook_event_name",
        "tool_name",
        "session_id",
        "transcript_path",
        "notification_type",
    ] {
        let value = str_field(payload, key);
        let usable = match key {
            "session_id" => is_conversation_id(&value),
            "transcript_path" => is_transcript_path(&value),
            _ => !value.is_empty(),
        };
        if usable {
            out.insert(key.to_string(), Value::String(value));
        }
    }
    if let Some(input) = payload.get("tool_input") {
        let target = [
            "file_path",
            "path",
            "command",
            "pattern",
            "url",
            "description",
            "prompt",
        ]
        .iter()
        .find_map(|k| input.get(*k).and_then(|v| v.as_str()))
        .map(str::to_string)
        .unwrap_or_else(|| input.to_string());
        out.insert("target".into(), Value::String(clip(&target, MAX_PREVIEW)));
    }
    for key in ["prompt", "message", "last_assistant_message"] {
        let value = str_field(payload, key);
        if !value.is_empty() {
            out.insert(key.to_string(), Value::String(clip(&value, MAX_PREVIEW)));
        }
    }
    if let Some(response) = payload.get("tool_response") {
        let failed = response
            .get("success")
            .and_then(|v| v.as_bool())
            .map(|ok| !ok)
            .or_else(|| response.get("is_error").and_then(|v| v.as_bool()))
            .unwrap_or(false);
        out.insert("failed".into(), Value::Bool(failed));
    }
    Value::Object(out)
}

fn emit(app: &AppHandle, mut event: Value) {
    if let Some(obj) = event.as_object_mut() {
        obj.insert("at".into(), json!(now_ms()));
    }
    if let Err(e) = app.emit(EVENT, &event) {
        eprintln!("[orchestra] failed to emit event: {e}");
    }
}

/// Optional short spawn setting (`--account`, `--model`, `--effort`); empty means "not given".
fn opt_field(value: &Value, key: &str) -> Value {
    let text = clip(&str_field(value, key), MAX_OPTION);
    if text.is_empty() {
        Value::Null
    } else {
        Value::String(text)
    }
}

/// Session named by a request body: missing, null or empty means the default session;
/// `None` when it is present but not a valid id.
fn body_session(payload: &Value) -> Option<String> {
    match payload.get("session") {
        None | Some(Value::Null) => Some(DEFAULT_SESSION.to_string()),
        Some(Value::String(session)) if session.is_empty() => Some(DEFAULT_SESSION.to_string()),
        Some(Value::String(session)) if is_valid_id(session) => Some(session.clone()),
        Some(_) => None,
    }
}

fn error(status: u16, message: &str) -> Routed {
    Routed {
        status,
        body: json!({ "error": message }).to_string(),
        event: None,
    }
}

/// Result of routing one `/orchestra/<action>` call: the HTTP reply plus the event to emit.
struct Routed {
    status: u16,
    body: String,
    event: Option<Value>,
}

/// Pure routing (no app handle) so it can be unit tested and cannot touch the listener.
/// Spawned worker ids come from `counters`.
fn route(url: &str, body: &str, counters: &Counters) -> Routed {
    let path = url
        .trim_start_matches("/orchestra/")
        .split('?')
        .next()
        .unwrap_or("");

    if let Some(rest) = path.strip_prefix("hook/") {
        // `hook/<session>/<agent>`; the legacy `hook/<agent>` belongs to the default session.
        let (session, agent_id) = rest.split_once('/').unwrap_or((DEFAULT_SESSION, rest));
        if !is_valid_id(session) {
            return error(400, "invalid session id");
        }
        if !is_valid_id(agent_id) {
            return error(400, "invalid agent id");
        }
        let payload: Value = serde_json::from_str(body).unwrap_or(Value::Null);
        return Routed {
            status: 200,
            body: "{}".into(),
            event: Some(json!({
                "kind": "hook",
                "session": session,
                "agent_id": agent_id,
                "hook": summarize_hook(&payload),
            })),
        };
    }

    let payload: Value = match serde_json::from_str(body) {
        Ok(v) => v,
        Err(e) => return error(400, &format!("expected JSON: {e}")),
    };
    let Some(session) = body_session(&payload) else {
        return error(400, "invalid session id");
    };

    match path {
        "report" => {
            let agent_id = str_field(&payload, "agent_id");
            if !is_valid_id(&agent_id) {
                return error(400, "invalid agent_id");
            }
            // PowerShell may send the number as a string; accept both.
            let progress = payload
                .get("progress")
                .and_then(|v| v.as_i64().or_else(|| v.as_str()?.trim().parse().ok()))
                .map(|p| p.clamp(0, 100));
            let status = str_field(&payload, "status").to_lowercase();
            let status = STATUSES.contains(&status.as_str()).then_some(status);
            let (note, clipped) = clip_flagged(&str_field(&payload, "note"), MAX_PREVIEW);
            Routed {
                status: 200,
                body: ok_body(json!({ "ok": true }), clipped, MAX_PREVIEW),
                event: Some(json!({
                    "kind": "report",
                    "session": session,
                    "agent_id": agent_id,
                    "progress": progress,
                    "status": status,
                    "note": note,
                })),
            }
        }
        "message" => {
            let from = str_field(&payload, "from");
            let to = str_field(&payload, "to");
            let (text, clipped) = clip_flagged(&str_field(&payload, "text"), MAX_TEXT);
            if !is_valid_id(&from) || !is_valid_id(&to) || text.is_empty() {
                return error(400, "message needs from, to and text");
            }
            Routed {
                status: 200,
                body: ok_body(json!({ "ok": true }), clipped, MAX_TEXT),
                event: Some(json!({
                    "kind": "message",
                    "session": session,
                    "from": from,
                    "to": to,
                    "text": text,
                })),
            }
        }
        "spawn" => {
            let from = str_field(&payload, "from");
            if from != "orchestrator" {
                return error(403, "only the orchestrator can spawn workers");
            }
            let (task, clipped) = clip_flagged(&str_field(&payload, "task"), MAX_TEXT);
            if task.is_empty() {
                return error(400, "spawn needs a task");
            }
            let area = clip(&str_field(&payload, "area"), 24);
            let after: Vec<String> = match payload.get("after") {
                Some(Value::Array(items)) => items
                    .iter()
                    .filter_map(|v| v.as_str())
                    .filter(|s| is_valid_id(s))
                    .map(str::to_string)
                    .collect(),
                Some(Value::String(s)) if is_valid_id(s) => vec![s.clone()],
                _ => Vec::new(),
            };
            let id = format!("claude-{}", counters.next(&session));
            // A one-account session drops `--account`; the reply tells the orchestrator why.
            let (account, account_ignored) =
                crate::orchestra_accounts::spawn_account(&session, opt_field(&payload, "account"));
            let mut reply = json!({ "id": id });
            if let Some(notice) = &account_ignored {
                reply["account_ignored"] = json!(notice);
            }
            Routed {
                status: 200,
                body: ok_body(reply, clipped, MAX_TEXT),
                event: Some(json!({
                    "kind": "spawn",
                    "session": session,
                    "id": id,
                    "area": area,
                    "task": task,
                    "after": after,
                    "account": account,
                    "account_ignored": account_ignored,
                    "model": opt_field(&payload, "model"),
                    "effort": opt_field(&payload, "effort"),
                })),
            }
        }
        // `orch note`: an agent's decision and its why, kept by the scribe as session material.
        "note" => {
            let agent_id = str_field(&payload, "agent_id");
            if !is_valid_id(&agent_id) {
                return error(400, "invalid agent_id");
            }
            let (text, clipped) = clip_flagged(&str_field(&payload, "text"), MAX_TEXT);
            if text.is_empty() {
                return error(400, "note needs text");
            }
            Routed {
                status: 200,
                body: ok_body(json!({ "ok": true }), clipped, MAX_TEXT),
                event: Some(json!({
                    "kind": "note",
                    "session": session,
                    "agent_id": agent_id,
                    "text": text,
                })),
            }
        }
        _ => error(404, "unknown orchestra action"),
    }
}

/// Handles `/orchestra/<action>`; returns the HTTP status and a JSON body.
///
/// This runs on the shared agent listener thread, so it must never take it down: a
/// failure here becomes a 500 reply instead of killing the listener (dev builds unwind)
/// and every route is written to be panic-free for release builds (`panic = "abort"`).
pub fn handle(app: &AppHandle, url: &str, body: &str) -> (u16, String) {
    let routed = std::panic::catch_unwind(|| route(url, body, &COUNTERS)).unwrap_or_else(|_| {
        eprintln!("[orchestra] route panicked for {url}");
        error(500, "internal orchestra error")
    });
    if let Some(event) = routed.event {
        if let Some(notice) = event.get("account_ignored").and_then(Value::as_str) {
            let _ =
                crate::diagnostics::append_spawn_log(app, &format!("[orchestra] spawn: {notice}"));
        }
        emit(app, event);
    }
    (routed.status, routed.body)
}

